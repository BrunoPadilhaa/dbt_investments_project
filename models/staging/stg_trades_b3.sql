
WITH raw_trades_b3 AS (
    SELECT
        TO_DATE(TRADE_DATE) AS TRADE_DATE,
        TRANSACTION_TYPE,
        IFF(ENDSWITH(ASSET_CODE,'F'), LEFT(ASSET_CODE, LENGTH(ASSET_CODE)-1), ASSET_CODE) AS ASSET_CODE,
        TO_DECIMAL(QUANTITY,10,2) AS QUANTITY,
        TO_DECIMAL(PRICE,10,2) AS PRICE,
        TO_DECIMAL(AMOUNT,10,2) AS AMOUNT,
        SOURCE_FILE,
        SOURCE_SYSTEM,
        LOAD_TS
    FROM {{source('raw', 'raw_trades_b3')}}
)

SELECT
    TRADE_DATE,
    TRANSACTION_TYPE,
    ASSET_CODE,
    CASE
        WHEN TRANSACTION_TYPE = 'Venda' THEN -QUANTITY
        ELSE QUANTITY
    END AS QUANTITY,
    PRICE,
     CASE
        WHEN TRANSACTION_TYPE = 'Venda' THEN -AMOUNT
        ELSE AMOUNT
    END AS AMOUNT,
    SOURCE_FILE,
    SOURCE_SYSTEM,
    LOAD_TS
FROM raw_trades_b3