WITH asset AS ( 
    SELECT
        ASSE.ASSET_CODE
    ,   ASSET_DTL.ASSET_NAME
    ,   ASSET_DTL.ASSET_COUNTRY
    ,   INVESTMENT_COUNTRY
    ,   ASSET_DTL.SOURCE_ASSET_SHORTNAME
    ,   ASSET_DTL.SOURCE_QUOTE_TYPE
    ,   ASSET_DTL.SECTOR
    ,   ASSD.ASSET_CLASS
    ,   ASSET_DTL.INDUSTRY
    ,   ASSET_DTL.EXCHANGE
    ,   ASSD.SOURCE_SYSTEM
    ,   ASSD.LOAD_TS

    FROM {{ ref('stg_asset') }} asse

    LEFT
    JOIN {{ ref('stg_asset_mapping') }} assd
    ON LOWER(asse.ASSET_CODE) = LOWER(assd.ASSET_CODE)

    LEFT JOIN {{ ref('stg_asset_details') }} ASSET_DTL
        ON  lower(ASSE.ASSET_CODE)        = lower(ASSET_DTL.ASSET_CODE)
        AND lower(ASSD.ASSET_CODE_SYSTEM) = lower(ASSET_DTL.ASSET_CODE_SYSTEM)
)

SELECT
    ASSE.ASSET_CODE AS ORIGINAL_ASSET_CODE,
    COALESCE(ASSET_CONV.CURRENT_ASSET_CODE, ASSE.ASSET_CODE) AS CURRENT_ASSET_CODE,
    ASSE.ASSET_NAME, 
    ASSE.ASSET_COUNTRY,
    ASSE.INVESTMENT_COUNTRY,
    ASSE.SOURCE_ASSET_SHORTNAME,
    ASSE.SOURCE_QUOTE_TYPE,
    ASSE.SECTOR,
    ASSE.ASSET_CLASS,
    ASSE.INDUSTRY,
    ASSE.EXCHANGE,
    ASSE.SOURCE_SYSTEM,
    ASSE.LOAD_TS
FROM asset ASSE
LEFT JOIN {{ref('stg_asset_conversion_mapping')}} ASSET_CONV
    ON LOWER(ASSE.ASSET_CODE) = LOWER(ASSET_CONV.RAW_ASSET_CODE)
